    long double key_rate_percent(Date date) {
        long double result = KEY_RATES[0].percent;
        for (const auto& s : KEY_RATES) {
            if (Date::from_ymd(s.y, s.m, s.d) <= date) result = s.percent;
            else break;
        }
        return result;
    }

